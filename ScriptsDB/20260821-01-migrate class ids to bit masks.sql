UPDATE "user"
SET class_id = CASE class_id
    WHEN 1 THEN 1
    WHEN 2 THEN 2
    WHEN 3 THEN 4
    WHEN 4 THEN 8
    WHEN 5 THEN 16
    WHEN 6 THEN 32
    WHEN 7 THEN 64
    WHEN 8 THEN 128
    WHEN 9 THEN 256
    WHEN 10 THEN 512
    WHEN 11 THEN 1024
    WHEN 12 THEN 2048
END
WHERE class_id BETWEEN 1 AND 12;